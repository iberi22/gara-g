//! Domain models for the Copilot Engine

use serde::{Deserialize, Serialize};
use std::fmt;

/// Risk levels for the vehicle's surroundings
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Serialize, Deserialize)]
pub enum RiskLevel {
    Low,
    Medium,
    High,
    Critical,
}

impl fmt::Display for RiskLevel {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            RiskLevel::Low => write!(f, "Low"),
            RiskLevel::Medium => write!(f, "Medium"),
            RiskLevel::High => write!(f, "High"),
            RiskLevel::Critical => write!(f, "Critical"),
        }
    }
}

/// Alert severity levels
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Serialize, Deserialize)]
pub enum AlertSeverity {
    Info,
    Warning,
    Emergency,
}

/// A safety alert generated by the Copilot Engine
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct Alert {
    pub id: String,
    pub severity: AlertSeverity,
    pub message: String,
    pub source: String,
    pub timestamp: i64,
}

/// Specialized safety agents that feed into the Copilot Engine
#[derive(Debug, Clone, Serialize, Deserialize)]
pub enum AgentType {
    Vision,      // AI Camera analysis
    Audio,       // Sound event detection
    Telemetry,   // Internal vehicle data (G-force, etc.)
    V2V,         // Communication from other vehicles
    System,      // Internal engine alerts
}

/// Information about a specific agent in the orchestration
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct CopilotAgentInfo {
    pub agent_type: AgentType,
    pub name: String,
    pub is_active: bool,
    pub last_update: i64,
}
